import { settings } from './settings';

export type Lang = 'bs' | 'en';

export const LANGUAGES: Array<{ id: Lang; label: string }> = [
  { id: 'bs', label: 'Bosanski' },
  { id: 'en', label: 'English' },
];

export function lang(): Lang {
  return settings.get().language === 'en' ? 'en' : 'bs';
}

export function locale(): string {
  return lang() === 'en' ? 'en-GB' : 'bs-BA';
}

export function t(text: string, vars?: Record<string, string | number>): string {
  let out = lang() === 'en' ? EN[text] ?? fromPattern(text) ?? text : text;
  if (vars) out = out.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
  return out;
}

// Poruke servera s ubačenim vrijednostima (npr. ime polja).
const PATTERNS: Array<[RegExp, string]> = [
  [/^Neispravan (.+)\.$/, 'Invalid $1.'],
  [/^Polje "(.+)" je obavezno\.$/, 'The field "$1" is required.'],
  [/^Polje "(.+)" je predugo \(max (\d+)\)\.$/, 'The field "$1" is too long (max $2).'],
  [/^Polje "(.+)" je prekratko \(min (\d+)\)\.$/, 'The field "$1" is too short (min $2).'],
  [/^Polje "(.+)" mora biti tekst\.$/, 'The field "$1" must be text.'],
  [/^Poruka je preduga \(max (\d+) znakova\)\.$/, 'The message is too long (max $1 characters).'],
];

function fromPattern(text: string): string | undefined {
  for (const [re, en] of PATTERNS) if (re.test(text)) return text.replace(re, en);
  return undefined;
}

